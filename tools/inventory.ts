// Every installed app (system, local, snap, flatpak) → its Icon= and where the *installed* Frost resolves it:
// Frost art, the personal overlay, an inherited theme, or an absolute path no theme can touch.
//   bun run inventory [--md docs/INVENTORY.md]
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { ROOT, THEME, flag } from "./lib";

const DIRS = ["/usr/share/applications", join(homedir(), ".local/share/applications"),
  "/var/lib/flatpak/exports/share/applications", "/var/lib/snapd/desktop/applications"];

type App = { id: string; name: string; icon: string };
const apps = new Map<string, App>();
for (const dir of DIRS) {
  if (!existsSync(dir)) continue;
  for (const f of readdirSync(dir).filter((f) => f.endsWith(".desktop"))) {
    const text = readFileSync(join(dir, f), "utf8");
    const entry = text.split(/^\[/m).find((s) => s.startsWith("Desktop Entry]")) ?? "";
    const get = (k: string) => entry.match(new RegExp(`^${k}=(.*)$`, "m"))?.[1]?.trim() ?? "";
    if (get("NoDisplay") === "true" || get("Hidden") === "true" || get("Type") !== "Application") continue;
    apps.set(f, { id: f, name: get("Name"), icon: get("Icon") });
  }
}

const list = [...apps.values()].sort((a, b) => a.name.localeCompare(b.name));
const named = list.filter((a) => a.icon && !a.icon.startsWith("/"));
const res = Bun.spawnSync(["python3", join(ROOT, "tools/lookup.py"), THEME, ...named.map((a) => a.icon), "--sizes", "48", "--json"]);
const rows: { name: string; scale: number; path: string | null }[] = JSON.parse(res.stdout.toString() || "[]");
const where = new Map(rows.filter((r) => r.scale === 1).map((r) => [r.name, r.path ?? ""]));

const status = (a: App) => {
  if (!a.icon) return "no icon";
  if (a.icon.startsWith("/")) return "absolute path (unthemable)";
  const p = where.get(a.icon) ?? "";
  if (p.includes(`/${THEME}/`)) return readlinkish(p) ? "overlay (official)" : "Frost";
  return p ? `inherited: ${p.match(/\/icons\/([^/]+)\//)?.[1] ?? p}` : "missing";
};
function readlinkish(p: string) {
  try { return Bun.spawnSync(["readlink", p]).stdout.toString().startsWith("/opt/"); } catch { return false; }
}

const lines = ["| App | Icon= | Resolves to |", "|---|---|---|", ...list.map((a) => `| ${a.name} | \`${a.icon || "—"}\` | ${status(a)} |`)];
const counts = list.reduce<Record<string, number>>((m, a) => { const k = status(a).split(":")[0]; m[k] = (m[k] ?? 0) + 1; return m; }, {});
const summary = Object.entries(counts).map(([k, v]) => `${k}: ${v}`).join(" · ");
const out = flag("md");
if (out) {
  writeFileSync(out, `# App inventory\n\nGenerated by \`bun run inventory --md ${out}\` against the installed theme. ${summary}\n\n${lines.join("\n")}\n`);
  console.log(`inventory: ${list.length} apps → ${out} (${summary})`);
} else {
  console.log(lines.join("\n"));
  console.log(`\n${list.length} apps — ${summary}`);
}
