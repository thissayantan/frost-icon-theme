// docs/COVERAGE.md: which commonly requested names Hyaline ships and which inherit (and from where),
// resolved by real GTK against dist/ via tools/lookup.py.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { DIST, ROOT, THEME, aliases, sources } from "./lib";

/** Names Files/GTK apps ask for most, grouped as in DESIGN §6. Not exhaustive — the point is to be honest. */
const WATCH: Record<string, string[]> = {
  Folders: [
    "folder", "folder-open", "folder-documents", "folder-download", "folder-music", "folder-pictures",
    "folder-videos", "folder-templates", "folder-publicshare", "folder-desktop", "user-desktop", "user-home",
    "folder-remote", "folder-drag-accept", "inode-directory", "folder-visiting", "folder-saved-search", "folder-new",
  ],
  Places: [
    "user-trash", "user-trash-full", "user-bookmarks", "network-workgroup", "network-server",
    "start-here", "network-wired", "folder-cloud",
  ],
  Mimetypes: [
    "text-x-generic", "application-x-generic", "application-pdf", "image-x-generic", "audio-x-generic",
    "video-x-generic", "package-x-generic", "application-zip", "application-x-tar", "text-x-script",
    "text-html", "x-office-document", "x-office-spreadsheet", "x-office-presentation", "application-x-executable",
    "font-x-generic", "text-x-python", "application-json", "image-svg+xml", "application-x-deb",
  ],
  Devices: ["drive-harddisk", "drive-removable-media", "computer", "phone", "printer", "camera-photo"],
  Apps: ["org.gnome.Nautilus", "org.gnome.Terminal", "org.gnome.Settings", "org.gnome.TextEditor", "org.gnome.Calculator"],
};

type Row = { name: string; size: number; scale: number; path: string | null; own: boolean };

if (import.meta.main) {
  const shipped = new Set(sources().map((s) => s.name));
  const alias = new Map<string, string>();
  for (const [t, names] of Object.entries(aliases())) if (shipped.has(t)) for (const n of names) alias.set(n, t);
  const names = [...new Set([...Object.values(WATCH).flat(), ...shipped, ...alias.keys()])];

  const res = Bun.spawnSync(["python3", join(ROOT, "tools/lookup.py"), THEME, ...names, "--search-path", DIST, "--sizes", "48", "--json"]);
  const rows: Row[] = JSON.parse(res.stdout.toString() || "[]");
  const where = new Map(rows.filter((r) => r.scale === 1).map((r) => [r.name, r]));
  const from = (p: string | null) => (p ? p.match(/\/icons\/([^/]+)\//)?.[1] ?? p.split("/").slice(-4, -3)[0] : "—");

  const out: string[] = [
    "# Coverage",
    "",
    "Generated by `bun run coverage` — do not edit. Each name is resolved by real GTK 4 (`tools/lookup.py`,",
    "48 px) against the current build. **Shipped** = Hyaline's own art; **alias** = a symlink to shipped art;",
    "**inherited** = falls through `Inherits=Papirus,Adwaita,hicolor` by design (ADR-002).",
    "",
    `Hyaline ships **${shipped.size}** icons and **${alias.size}** aliases.`,
    "",
  ];
  const groups = { ...WATCH, Other: [...shipped, ...alias.keys()].filter((n) => !Object.values(WATCH).flat().includes(n)) };
  for (const [group, list] of Object.entries(groups)) {
    if (!list.length) continue;
    out.push(`## ${group}`, "", "| Name | Status | Resolved from |", "|---|---|---|");
    for (const n of list) {
      const r = where.get(n);
      const status = shipped.has(n) ? "✅ shipped" : alias.has(n) ? `↪ alias of \`${alias.get(n)}\`` : r?.path ? "inherited" : "⚠ missing";
      out.push(`| \`${n}\` | ${status} | ${r?.own ? THEME : from(r?.path ?? null)} |`);
    }
    out.push("");
  }
  writeFileSync(join(ROOT, "docs/COVERAGE.md"), out.join("\n"));
  console.log(`coverage: ${shipped.size} shipped, ${alias.size} aliases → docs/COVERAGE.md`);
}
